/* Build a small, local SVG sprite from the pinned Lucide static package. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const packageRoot = path.dirname(require.resolve('lucide-static/package.json'));
const icons = ['sparkles', 'panels-top-left', 'code-xml', 'chart-no-axes-combined', 'cloud', 'search', 'arrow-right', 'arrow-left', 'check', 'menu'];
const symbols = icons.map(name => {
  const source = fs.readFileSync(path.join(packageRoot, 'icons', `${name}.svg`), 'utf8');
  const content = source.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/)?.[1];
  if (!content) throw new Error(`Missing SVG content: ${name}`);
  return `<symbol id="${name}" viewBox="0 0 24 24">${content.trim()}</symbol>`;
});
fs.mkdirSync(path.join(root, 'assets'), { recursive: true });
fs.writeFileSync(path.join(root, 'assets', 'ui-icons.svg'), `<!-- Lucide icons. See /assets/lucide-license.txt. Generated by scripts/build-ui-icons.cjs. -->\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`);
fs.copyFileSync(path.join(packageRoot, 'LICENSE'), path.join(root, 'assets', 'lucide-license.txt'));
console.log(`Built ${icons.length} local UI icons.`);
